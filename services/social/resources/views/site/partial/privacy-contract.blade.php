  <p class="small text-muted">Effective July 27, 2026</p>
  <p>
    Mōchirīī Social is a private, non-federated space for verified guild members. Access is limited to verified members and authorized Mōchirīī stewards. Member profiles, photos, posts, and conversations are not published to outside social networks.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="information-we-handle">1. Information we handle</h2>
  <ul class="pl-4">
    <li>Guild identity information supplied by Mōchirīī when you sign in, including your account identifier, display name, email address, and current membership status. Mōchirīī Social does not receive your Mōchirīī password.</li>
    <li>Profile details, photos, posts, messages, and other content you choose to submit.</li>
    <li>Interactions needed to provide the service, such as follows, reactions, reports, and account preferences.</li>
    <li>Security and operational records, such as session details, IP address, browser information, request timestamps, and moderation or support history.</li>
  </ul>

  <h2 class="h5 font-weight-bold mt-5" id="how-we-use-information">2. How we use information</h2>
  <p>We use this information to:</p>
  <ul class="pl-4">
    <li>authenticate verified members and provide profiles, photos, conversations, and account features;</li>
    <li>protect accounts, investigate abuse, enforce guild rules, and maintain service reliability;</li>
    <li>deliver account notices and respond to support, privacy, and safety requests; and</li>
    <li>meet legal obligations and preserve the rights and safety of members and Mōchirīī.</li>
  </ul>

  <h2 class="h5 font-weight-bold mt-5" id="member-visibility">3. Member visibility and conversations</h2>
  <p>
    Information and content are visible only within Mōchirīī Social according to the audience and feature you choose. Private here means restricted to the verified guild community; it does not mean every submission is hidden from every other member. Direct conversations are intended for their participants, but they are not end-to-end encrypted. Authorized Mōchirīī stewards may access information when necessary for safety, moderation, support, security, or legal compliance.
  </p>
  <p>
    Other members may save, copy, or share what they can see. Do not submit passwords, payment details, recovery codes, or other highly sensitive information.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="outside-sharing">4. Outside sharing and service providers</h2>
  <p>
    Mōchirīī does not sell member information, use it for outside advertising, federate member content, or publish it to outside social networks. Limited service providers may process information only as needed to host, secure, store, or deliver Mōchirīī Social on our behalf. We may also disclose information when required by law or when reasonably necessary to protect members, Mōchirīī, or the public.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="cookies-and-security">5. Cookies and security</h2>
  <p>
    Mōchirīī Social uses cookies and similar local storage for sign-in sessions, security, preferences, and essential service operation. Connections use HTTPS. We apply access controls and operational safeguards, but no online service can guarantee absolute security.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="retention-and-choices">6. Retention and your choices</h2>
  <p>
    We keep account information and content while your account is active or as needed to provide Mōchirīī Social. Some security records, backups, moderation records, and legally required information may remain for a limited period after content or an account is removed. Available account settings let you manage profile information, sessions, content, and account deletion. You may also contact Mōchirīī to request access, correction, deletion, or help with a privacy concern, subject to applicable law and necessary security records.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="eligibility-and-updates">7. Eligibility and policy updates</h2>
  <p>
    Mōchirīī Social is for verified guild members who meet the guild's eligibility rules and applicable age requirements. We may update this policy when the service or legal requirements change. Material changes will be posted here with a revised effective date.
  </p>

  <h2 class="h5 font-weight-bold mt-5" id="contact-us">8. Contact Mōchirīī</h2>
  <p class="mb-0">
    For privacy, safety, or account questions, use the <a href="https://mochirii.com/contact">Mōchirīī contact page</a>.
  </p>
